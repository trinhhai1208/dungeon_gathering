using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using DungeonGathering.Catalog;
using UnityEditor;
using UnityEngine;

namespace DungeonGathering.EditorTools
{
    /// <summary>
    /// Sinh enum <see cref="SkillId"/> từ SkillLibrary: entry chưa có số được cấp số mới (lớn nhất + 1), số cũ giữ nguyên
    /// → enum đã gán trên hero / quái không bị lệch khi thêm skill. Tên enum = key viết PascalCase.
    /// </summary>
    public static class SkillIdGenerator
    {
        public const string LibraryPath = "Assets/Project/Data/Skills/SkillLibrary.asset";
        const string EnumPath = "Assets/Project/Scripts/Catalog/Skills/SkillId.cs";

        [MenuItem("Tools/Dungeon Gathering/Skills/Generate SkillId")]
        public static void GenerateMenu()
        {
            var lib = AssetDatabase.LoadAssetAtPath<SkillLibrarySO>(LibraryPath);
            if (lib == null) { Debug.LogError($"[Skills] Không thấy {LibraryPath}"); return; }
            Debug.Log(Generate(lib));
            AssetDatabase.Refresh();
        }

        [MenuItem("Tools/Dungeon Gathering/Skills/Select Skill Library")]
        public static void SelectLibrary() => Selection.activeObject = AssetDatabase.LoadAssetAtPath<SkillLibrarySO>(LibraryPath);

        /// <summary>Cấp số cho entry mới, kiểm tra trùng, ghi SkillId.cs. Trả về báo cáo.</summary>
        public static string Generate(SkillLibrarySO lib)
        {
            var log = new StringBuilder("[Skills] Generate SkillId\n");
            // Không tái dùng số của skill đã xóa: lấy max của (entry hiện có, số lớn nhất từng cấp, enum hiện tại).
            int highest = lib.skills.Where(e => e != null).Select(e => e.value).DefaultIfEmpty(0).Max();
            highest = Mathf.Max(highest, lib.highestIssuedValue, HighestInExistingEnum());
            int next = highest + 1;
            var usedValues = new HashSet<int>();
            var usedNames = new HashSet<string> { "None" };
            var lines = new List<(string name, int value, string comment)>();
            bool dirty = false;

            foreach (var e in lib.skills)
            {
                if (e == null) continue;
                if (string.IsNullOrWhiteSpace(e.key)) { log.AppendLine("  Bỏ qua entry không có key."); continue; }
                if (e.value <= 0 || usedValues.Contains(e.value)) { e.value = next++; dirty = true; }
                usedValues.Add(e.value);
                string name = ToEnumName(e.key);
                string unique = name;
                for (int i = 2; usedNames.Contains(unique); i++) unique = name + i;
                usedNames.Add(unique);
                if (unique != name) log.AppendLine($"  Key trùng tên enum: {e.key} → {unique}");
                string kind = e.skill == null ? "CHƯA GÁN SO" : e.skill.GetType().Name;
                lines.Add((unique, e.value, $"{e.key} · {kind}"));
            }
            if (next - 1 > lib.highestIssuedValue) { lib.highestIssuedValue = next - 1; dirty = true; }
            if (dirty) { EditorUtility.SetDirty(lib); AssetDatabase.SaveAssets(); }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Sinh bởi Tools ▸ Dungeon Gathering ▸ Skills ▸ Generate SkillId từ Data/Skills/SkillLibrary.asset.");
            sb.AppendLine("// Không sửa tay: thêm / đổi skill trong SkillLibrary rồi chạy lại menu. Số của mỗi skill cố định.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("namespace DungeonGathering.Catalog");
            sb.AppendLine("{");
            sb.AppendLine("    public enum SkillId");
            sb.AppendLine("    {");
            sb.AppendLine("        None = 0,");
            foreach (var l in lines.OrderBy(l => l.value))
                sb.AppendLine($"        /// <summary>{l.comment}</summary>\n        {l.name} = {l.value},");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            File.WriteAllText(EnumPath, sb.ToString().Replace("\r\n", "\n"));
            log.AppendLine($"Ghi {EnumPath}: {lines.Count} skill.");
            return log.ToString();
        }

        /// <summary>Số lớn nhất trong SkillId.cs hiện tại (bắt cả skill vừa bị xóa khỏi thư viện trước khi chạy lại).</summary>
        static int HighestInExistingEnum()
        {
            if (!File.Exists(EnumPath)) return 0;
            int max = 0;
            foreach (Match m in Regex.Matches(File.ReadAllText(EnumPath), @"=\s*(\d+)\s*,"))
                if (int.TryParse(m.Groups[1].Value, out int v)) max = Mathf.Max(max, v);
            return max;
        }

        public static string ToEnumName(string key)
        {
            var parts = Regex.Split(key.Trim(), "[^A-Za-z0-9]+").Where(p => p.Length > 0);
            var name = string.Concat(parts.Select(p => char.ToUpperInvariant(p[0]) + p.Substring(1)));
            if (name.Length == 0) name = "Skill";
            if (char.IsDigit(name[0])) name = "S" + name;
            return name;
        }
    }
}
